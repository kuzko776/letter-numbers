create or replace function public.fail(code int, msg text) returns void
language plpgsql set search_path = '' as $$
begin
  raise exception '%', msg using errcode = 'P0001', detail = code::text;
end $$;

create or replace function public.current_profile() returns public.profiles
language plpgsql security definer set search_path = '' as $$
declare p public.profiles;
begin
  select * into p from public.profiles where id = auth.uid() and active;
  if not found then perform public.fail(401, 'سجّل دخولك للمتابعة.'); end if;
  return p;
end $$;

create or replace function public.require_admin() returns public.profiles
language plpgsql security definer set search_path = '' as $$
declare p public.profiles := public.current_profile();
begin
  if p.role <> 'admin' then perform public.fail(403, 'هذه العملية متاحة للمدير.'); end if;
  return p;
end $$;

create or replace function public.me() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.profiles := public.current_profile();
begin
  return jsonb_build_object('id', p.id, 'name', p.name, 'email', p.email, 'role', p.role);
end $$;

create or replace function public.reserve_letter(p_subject text, p_request_id uuid) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  u public.profiles := public.current_profile();
  subj text := btrim(coalesce(p_subject, ''));
  prev public.letters;
  hy int;
  s int;
  l public.letters;
begin
  if subj = '' or length(subj) > 200 then
    perform public.fail(400, 'أدخل موضوع الخطاب بما لا يزيد على 200 حرف.');
  end if;
  select * into prev from public.letters where user_id = u.id and request_id = p_request_id;
  if found then
    if prev.subject <> subj then perform public.fail(409, 'يرتبط الطلب بحجز آخر.'); end if;
    return jsonb_build_object('number', to_char(prev.serial, 'FM0000') || '-' || to_char(prev.year % 100, 'FM00'),
      'subject', prev.subject, 'requestedBy', prev.requested_by, 'createdAt', prev.created_at);
  end if;
  select max(year) into hy from public.hijri_years
    where starts_on <= (now() at time zone 'Asia/Riyadh')::date;
  if hy is null then perform public.fail(500, 'تعذر تحديد السنة الهجرية.'); end if;
  perform pg_advisory_xact_lock(hy);
  select coalesce(max(serial), 0) + 1 into s from public.letters where year = hy;
  if s > 9999 then perform public.fail(409, 'تم بلوغ الحد السنوي لأرقام الخطابات.'); end if;
  insert into public.letters (year, serial, subject, user_id, requested_by, request_id)
    values (hy, s, subj, u.id, u.name, p_request_id) returning * into l;
  return jsonb_build_object('number', to_char(l.serial, 'FM0000') || '-' || to_char(l.year % 100, 'FM00'),
    'subject', l.subject, 'requestedBy', l.requested_by, 'createdAt', l.created_at);
end $$;

create or replace function public.list_letters(p_query text default '', p_offset int default 0) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  u public.profiles := public.current_profile();
  q text := lower(left(btrim(coalesce(p_query, '')), 200));
  off int := least(1000000, greatest(0, coalesce(p_offset, 0)));
  result jsonb;
begin
  select jsonb_build_object(
    'letters', coalesce(jsonb_agg(t.r order by t.rn) filter (where t.rn <= 25), '[]'::jsonb),
    'more', count(*) > 25)
  into result
  from (
    select row_number() over (order by year desc, serial desc) as rn,
      jsonb_build_object('number', to_char(serial, 'FM0000') || '-' || to_char(year % 100, 'FM00'),
        'subject', subject, 'requestedBy', requested_by, 'createdAt', created_at) as r
    from (
      select * from public.letters
      where (u.role = 'admin' or user_id = u.id)
        and (q = '' or strpos(lower(subject), q) > 0
             or strpos(to_char(serial, 'FM0000') || '-' || to_char(year % 100, 'FM00'), q) > 0)
      order by year desc, serial desc limit 26 offset off
    ) page
  ) t;
  return result;
end $$;

create or replace function public.list_employees() returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_admin();
  return (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'name', name, 'email', email, 'active', active)
    order by name, id), '[]'::jsonb) from public.profiles where role = 'employee');
end $$;

create or replace function public.create_employee(p_name text, p_email text, p_password text) returns void
language plpgsql security definer set search_path = '' as $$
declare
  nm text := btrim(coalesce(p_name, ''));
  em text := lower(btrim(coalesce(p_email, '')));
  uid uuid := gen_random_uuid();
begin
  perform public.require_admin();
  if nm = '' or length(nm) > 100 then perform public.fail(400, 'أدخل اسم الموظف بما لا يزيد على 100 حرف.'); end if;
  if em !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' or length(em) > 254 then
    perform public.fail(400, 'أدخل عنوانًا بصيغة بريد إلكتروني.');
  end if;
  if p_password is null or length(p_password) < 10 or length(p_password) > 128 then
    perform public.fail(400, 'أدخل كلمة مرور تتكون من 10 إلى 128 حرفًا.');
  end if;
  if exists (select 1 from auth.users where lower(email) = em) then
    perform public.fail(409, 'يوجد حساب بهذا البريد بالفعل.');
  end if;
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
    confirmation_token, recovery_token, email_change, email_change_token_new)
  values ('00000000-0000-0000-0000-000000000000', uid, 'authenticated', 'authenticated', em,
    extensions.crypt(p_password, extensions.gen_salt('bf')), now(),
    '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, created_at, updated_at, last_sign_in_at)
  values (gen_random_uuid(), uid, uid::text,
    jsonb_build_object('sub', uid::text, 'email', em, 'email_verified', true), 'email', now(), now(), now());
  insert into public.profiles (id, name, email, role) values (uid, nm, em, 'employee');
end $$;

create or replace function public.set_employee_active(p_id uuid, p_active boolean) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_admin();
  update public.profiles set active = p_active where id = p_id and role = 'employee';
  if not found then perform public.fail(404, 'حساب الموظف غير موجود.'); end if;
  update auth.users set banned_until = case when p_active then null else 'infinity'::timestamptz end where id = p_id;
  if not p_active then delete from auth.sessions where user_id = p_id; end if;
end $$;

create or replace function public.set_employee_password(p_id uuid, p_password text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform public.require_admin();
  if p_password is null or length(p_password) < 10 or length(p_password) > 128 then
    perform public.fail(400, 'أدخل كلمة مرور تتكون من 10 إلى 128 حرفًا.');
  end if;
  perform 1 from public.profiles where id = p_id and role = 'employee';
  if not found then perform public.fail(404, 'حساب الموظف غير موجود.'); end if;
  update auth.users set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf')) where id = p_id;
  delete from auth.sessions where user_id = p_id;
end $$;

-- Only callable from the SQL editor: turns an existing Auth user into the administrator.
create or replace function public.make_admin(p_email text, p_name text default 'مدير النظام') returns void
language plpgsql security definer set search_path = '' as $$
declare uid uuid;
begin
  if exists (select 1 from public.profiles where role = 'admin') then raise exception 'An administrator already exists'; end if;
  select id into uid from auth.users where lower(email) = lower(p_email);
  if uid is null then raise exception 'Create the user first in Authentication -> Users'; end if;
  insert into public.profiles (id, name, email, role) values (uid, p_name, lower(p_email), 'admin');
end $$;

